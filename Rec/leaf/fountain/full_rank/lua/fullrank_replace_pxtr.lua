  local plvtr = fullrank_ori_plvtr or 0.0
  local psvr = fullrank_ori_psvr or 0.0
  local pltr = fullrank_ori_pltr or 0.0
  local phtr = fullrank_ori_phtr or 0.0
  local pwtr = fullrank_ori_pwtr or 0.0
